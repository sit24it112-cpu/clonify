// --- New Batch Analysis ---

apiRouter.post('/analyze', (req: Request, res: Response) => {
  const startTime = Date.now();
  const {
    assignmentName = 'Untitled Assignment',
    batchId = `BATCH-${Date.now().toString(36).toUpperCase()}`,
    courseName = '',
    reviewerNotes = '',
    reviewThreshold = 0.78,
    submissions: rawSubmissions = []
  } = req.body;

  if (!Array.isArray(rawSubmissions) || rawSubmissions.length < 2) {
    return res.status(400).json({
      error: 'At least two valid submissions are required to perform similarity analysis.'
    });
  }

  // Maximum submission count check
  if (rawSubmissions.length > 50) {
    return res.status(400).json({
      error: 'Maximum 50 submissions per batch in this environment.'
    });
  }

  const analysisId = `analysis-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;
  const validSubmissions: CodeSubmission[] = [];
  const prepMap = new Map<string, PreprocessedSource>();
  const detectedLanguages = new Set<SupportedLanguage>();

  // Process & Validate Submissions
  for (let idx = 0; idx < rawSubmissions.length; idx++) {
    const item = rawSubmissions[idx];
    const filename = String(item.filename || `submission_${idx + 1}.py`).trim();
    const content = String(item.content || '').trim();
    const studentId = item.studentId ? String(item.studentId).trim() : undefined;

    const lang = detectLanguage(filename);
    if (!lang) {
      return res.status(400).json({
        error: `Unsupported file type for "${filename}". Only .py (Python) and .java (Java) files are supported.`
      });
    }

    if (content.length === 0) {
      return res.status(400).json({
        error: `Submission "${filename}" is empty. Please provide valid source code.`
      });
    }

    detectedLanguages.add(lang);
    const subId = `sub-${analysisId}-${idx + 1}`;
    const hash = crypto.createHash('sha256').update(content).digest('hex');

    const prep = preprocessCode(content, lang);
    prepMap.set(subId, prep);

    validSubmissions.push({
      id: subId,
      filename,
      language: lang,
      content,
      studentId,
      fileSize: Buffer.byteLength(content, 'utf8'),
      lineCount: prep.originalLines.length,
      tokenCount: prep.tokens.length,
      hash,
      parseStatus: prep.parseStatus,
      parseError: prep.parseError
    });
  }

  // Pairwise Comparison (Language-specific comparisons: Python with Python, Java with Java)
  const pairs: PairwiseResult[] = [];
  const allPreps = Array.from(prepMap.values());
  const effectiveThreshold = reviewThreshold > 1 ? reviewThreshold : reviewThreshold * 100;

  for (let i = 0; i < validSubmissions.length; i++) {
    for (let j = i + 1; j < validSubmissions.length; j++) {
      const subA = validSubmissions[i];
      const subB = validSubmissions[j];

      // Language isolation rule: compare same language
      if (subA.language === subB.language) {
        const prepA = prepMap.get(subA.id)!;
        const prepB = prepMap.get(subB.id)!;

        const pairResult = compareSubmissionPair(
          subA,
          subB,
          prepA,
          prepB,
          allPreps,
          effectiveThreshold,
          analysisId
        );
        pairs.push(pairResult);
      }
    }
  }

  // Sort pairs by highest similarity score first
  pairs.sort((a, b) => b.overallScore - a.overallScore);

  const totalPossiblePairs = (validSubmissions.length * (validSubmissions.length - 1)) / 2;
  const flaggedCount = pairs.filter(p => p.exceedsThreshold).length;
  const avgScore = pairs.length > 0
    ? Math.round((pairs.reduce((acc, p) => acc + p.overallScore, 0) / pairs.length) * 10) / 10
    : 0;

  const durationMs = Date.now() - startTime;

  const analysisSummary: AnalysisSummary = {
    id: analysisId,
    assignmentName,
    batchId,
    courseName,
    reviewerNotes,
    timestamp: new Date().toISOString(),
    submissionCount: validSubmissions.length,
    totalPossiblePairs,
    pairsAnalyzedCount: pairs.length,
    flaggedPairsCount: flaggedCount,
    averageSimilarity: avgScore,
    reviewThreshold: effectiveThreshold / 100,
    languages: Array.from(detectedLanguages),
    status: 'completed',
    candidateSearchMethod: totalPossiblePairs > 100 ? 'winnowing_filtered' : 'exhaustive',
    durationMs
  };

  // Persist to Database
  dbInstance.saveAnalysis(analysisSummary);
  dbInstance.saveSubmissions(validSubmissions, analysisId);
  dbInstance.savePairs(pairs);

  res.status(201).json({
    analysis: analysisSummary,
    pairs,
    submissions: validSubmissions
  });
});

// --- Pairwise & Evidence Endpoints ---

apiRouter.get('/pairs/:id', (req: Request, res: Response) => {
  const pair = dbInstance.getPair(req.params.id);
  if (!pair) {
    return res.status(404).json({ error: 'Pair not found' });
  }
  res.json(pair);
});

apiRouter.get('/pairs/:id/evidence', (req: Request, res: Response) => {
  const pair = dbInstance.getPair(req.params.id);
  if (!pair) {
    return res.status(404).json({ error: 'Pair not found' });
  }

  const subA = dbInstance.getSubmission(pair.submissionAId);
  const subB = dbInstance.getSubmission(pair.submissionBId);

  if (!subA || !subB) {
    return res.status(404).json({ error: 'Underlying submissions not found' });
  }

  const prepA = preprocessCode(subA.content, subA.language);
  const prepB = preprocessCode(subB.content, subB.language);

  res.json({
    pair,
    submissionA: {
      ...subA,
      cleanLines: prepA.cleanLines,
      normalizedString: prepA.normalizedString,
      tokenCount: prepA.tokens.length
    },
    submissionB: {
      ...subB,
      cleanLines: prepB.cleanLines,
      normalizedString: prepB.normalizedString,
      tokenCount: prepB.tokens.length
    },
    matchedRegions: pair.matchedRegions,
    contributions: pair.featureContributions,
    explanation: pair.explanation
  });
});

// --- Human Review Endpoints ---

apiRouter.get('/reviews', (req: Request, res: Response) => {
  const analysisId = req.query.analysisId ? String(req.query.analysisId) : undefined;
  const reviews = dbInstance.getReviews(analysisId);
  res.json(reviews);
});

apiRouter.post('/reviews', (req: Request, res: Response) => {
  const { pairId, analysisId, status, decisionNotes, reviewerId = 'Faculty Reviewer' } = req.body;

  if (!pairId || !analysisId || !status) {
    return res.status(400).json({ error: 'pairId, analysisId, and status are required' });
  }

  const existingReviews = dbInstance.getReviews(analysisId);
  const existing = existingReviews.find(r => r.pairId === pairId);

  const now = new Date().toISOString();
  const record: ReviewRecord = {
    id: existing ? existing.id : `rev-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
    pairId,
    analysisId,
    status,
    decisionNotes: decisionNotes || '',
    reviewerId,
    createdAt: existing ? existing.createdAt : now,
    updatedAt: now
  };

  dbInstance.saveReviewRecord(record);
  res.json({ success: true, review: record });
});

