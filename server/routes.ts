  res.setHeader('Content-Type', 'application/json');
  res.setHeader('Content-Disposition', `attachment; filename="Clonify_Report_${analysis.batchId}_${analysis.id}.json"`);
  res.send(JSON.stringify(exportPayload, null, 2));
